                  जन्मतःच ॐकाराचा उच्चार केला. त्यानंतर त्यांनी एकही शब्द बोलला नाही. अशीच सात वर्षे गेली. त्यांनी
                  खुणेनेच आपले मौजीबंधन करावे असे मातापित्यांना सुचविले. मौजीबंधन होताच त्यांच्या मुखातून वेदवाणी बाहेर
                  पडू लागली. तेव्हा सगळ्यांची खात्री झाली की हा बालक अवतारी पुरुष आहे.
                </p>
                <p>
                  वयाच्या आठव्या वर्षी माता-पित्यांचा आशीर्वाद घेऊन ते बद्रीकेदारला गेले. वाटेत काशी मुक्कामी त्यांची
                  गाठ कृष्णसरस्वती या वृद्ध संन्याशाशी पडली. कृष्णसरस्वतींनी नरहरीला मठपरंपरेप्रमाणे संन्यासदीक्षा दिली.
                  उत्तरेत शिक्षण पूर्ण केल्यावर श्री नृसिंह सरस्वती दक्षिणेस प्रथम लाडकारंजा येथे आले. माता-पित्यांना
                  भेटले. त्यानंतर ते त्र्यंबकेश्वर, नाशिक, परळी वैजनाथ, औदुंबर, अमरापूर या गावी राहिले. अमरापूर हे गांव
                  कृष्णा-पंचगंगा संगमावर आहे. तेथे श्री नृसिंह सरस्वती बारा वर्षे राहिले. त्यांच्या या गावातील प्रदीर्घ
                  निवासामुळेच या गावाला नरसोबाची वाडी किंवा नृसिंहवाडी हे नाव प्राप्त झाले.
                </p>
                <p>
                  त्यानंतर ते चोवीस वर्षे गाणगापुरला राहिले. त्या वेळी बिदरचा बादशहा अल्लाउद्दीन (दुसरा) याने त्यांची
                  पूजा केली. त्यानंतर ते आपल्या शिष्यांसह श्रीशैलकडे निघाले.
                </p>
                <p>
                  श्री नृसिंह सरस्वतींनी श्रीपाद श्रीवल्लभांचेच कार्य पुढे चालवले आणि दत्तभक्तीचा विस्तार केला. त्यांना
                  दीर्घायुष्य लाभले. संपूर्ण भारतामध्ये त्यांनी संचार केला. त्यांच्या मोठा शिष्यवर्ग तयार झाला. त्यांचे
                  प्रमुख सात शिष्य होते. माधव सरस्वती, कृष्ण सरस्वती, बाळकृष्ण सरस्वती, उपेंद्र सरस्वती, सदानंद सरस्वती,
                  ज्ञानज्योती सरस्वती आणि सिद्ध सरस्वती. या सर्वानी दत्त परंपरेचा सर्वत्र प्रचार आणि प्रसार केला.
                </p>
                <p>
                  श्री नृसिंह सरस्वतींनी औदुंबर, नृसिंहवाडी, गाणगापूर या ठिकाणी तपश्चर्या केली. ही ठिकाणे दत्त
                  संप्रदायातील पवित्र तीर्थक्षेत्रे बनली. हजारो भाविक तेथे अनुष्ठाने, जप, तप, पारायणे करतात. त्यातून
                  त्यांना ऐहिक आणि पारलौकिक कल्याणाचा लाभ होतो.
                </p>
                <p>
                  महाराष्ट्रातील दत्त संप्रदायाचा प्रारंभ श्री नृसिंह सरस्वतींच्या अवतारानंतर झाला असे मानले जाते. श्री
                  नृसिंह सरस्वतींनी शिव, विष्णू, देवी, गणेश आणि नृसिंह यांच्या उपासनेचा उपदेश केला. त्यांच्यामुळेच
                  महाराष्ट्रात दत्तोपासना लोकप्रिय झाली.
                </p>
