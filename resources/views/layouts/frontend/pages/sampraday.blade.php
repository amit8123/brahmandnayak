                <p class="fw-bold">
                  श्री स्वामी समर्थ - ‘ब्रह्मांडनायक’
                </p>
                <p>
                  श्री स्वामी समर्थांच्या जन्मतिथी, जन्मस्थान, आई-वडील, गुरु याबद्दल काहीच माहिती उपलब्ध नाही. त्यामुळे
                  दिगंबर वेषात असलेल्या महाराजांचा चैत्र शुद्ध द्वितीया हा प्रकटदिन म्हणून साजरा केला जातो. सर्वाना
                  माहीत असलेल्या इ.स. १८५६ ते १८७८ ह्या बावीस वर्षाच्या कालावधीत श्री स्वामी समर्थानी अक्कलकोट येथेच
                  राहून अनेक लीला केल्या. अनेक भक्तांचा उद्धार केला. श्री स्वामी समर्थ हे दत्त संप्रदायातील श्री
                  दत्तात्रेयांचे चौथे अवतार मानले जातात. दत्त संप्रदायाची परंपरा फार मोठी आहे. श्री गुरु दत्तात्रेय -
                  श्री श्रीपाद श्रीवल्लभ - श्री नृसिंह सरस्वती - श्री स्वामी समर्थ अशी मानली जाते. स्वामी महाराजांचा
                  शिष्य परिवार पाहिला कि लक्षात येते ही परंपरा श्री स्वामी समर्थ महाराजांपासून पुढे मोठ्या प्रमाणात
                  प्रचारात आली.
                </p>
                <p>
                  स्वामी महाराजांच्या प्रकटीकरणाविषयी दत्त संप्रदायात एक आख्यायिका प्रसिद्ध आहे. श्री नृसिंह सरस्वती
                  आपल्या अवतार समाप्तीच्या वेळी श्रीशैल्य येथून कर्दळीवनामध्ये गेले. तेथे ते तपश्चर्येला बसले. येथूनच
                  श्री स्वामी समर्थ प्रकट झाले असे म्हणतात. श्री नृसिंह सरस्वतीचे निर्गमन आणि श्री स्वामी समर्थांचे
                  प्रकट होणे यात साडेतीनशे वर्षांचा काळ लोटला.
                </p>
                <p>
                  श्री नृसिंह सरस्वती कर्दळीवनात तपश्चर्येला बसले असताना त्यांच्याभोवती वारूळ तयार झाले. एके दिवशी एका
                  लाकूडतोडय़ाचा लाकूड तोडताना कुऱ्हाडीचा घाव चुकला आणि तो वारुळावर पडला. त्या वारुळातून श्री स्वामी समर्थ
                  प्रकट झाले असे सांगितले जाते. लाकडे तोडताना कुऱ्हाडीचा घाव वारुळावर बसला आणि तो स्वामींच्या मांडीला
                  लागून स्वामी समाधीतून जागे झाले. तो कुऱ्हाडीचा वार त्यांचे मांडीवर स्पष्ट दिसत असे.
                </p>
                <p>
                  पहिल्यांदा स्वामी महाराज अक्कलकोटला आले ते खंडोबाच्या मंदिरात राहिले. तिथे ते तीन दिवस उपाशी होते. ही
                  गोष्ट चोळप्पाने पहिली. त्यांच्या मनात स्वामींबद्दल प्रेम निर्माण झाले. चोळप्पा स्वामींना घेऊन ते
                  स्वतःच्या घरी आले. त्यांनी स्वामींना जेवायला दिले. तेव्हापासून स्वामी चोळप्पाच्या घरी राहिले ते
                  कायमचे. पहिल्यांदा जेव्हा स्वामी चोळप्पाच्या घरी आले त्या दिवशी घरातील लोकांनी 'कोणीतरी वेडा घरात आणून
                  ठेवला आहे' असे सारखे बोलून चोळप्पाना भंडावून सोडले. पण चोळप्पांनी महाराजांच्या सेवेत जराही कसूर केली
                  नाही. म्हणून चोळप्पा महाराजांच्या अंतरंगातील शिष्य झाले.
                </p>
                <p>
                  स्वामी अक्कलकोटला आले आणि चोळप्पांच्या घरी राहू लागले. जे लोक स्वामींना पाहत किंवा भेटत ते स्वामींना
                  कुतूहलाने "आपण कोण आणि कुठून आलात स्वामी?" असे विचारीत. त्यावेळी स्वामी सांगत, ‘मूळ पुरुष वडाचे झाड,
                  दत्तनगर वसतिस्थान, आम्हीं यजुर्वेदी ब्राह्मण, गोत्र काश्यप, रास मीन आणि नाव नृसिंहभान. ‘प्रथम आम्ही
                  कर्दळीवनातून निघालो. पुढे कलकत्ता शहर पाहिले. बांगलादेश हिंडून कालीमातेचे दर्शन घेतले. नंतर
                  गंगाकिनाऱ्याने फिरत हरिद्वार आणि केदारेश्वर पाहिले. पुढे आम्ही गोदातटी आलो. गोदावरीचे स्नान करून
                  हैद्राबादेस गेलो. तेथे काही दिवस राहून नंतर पंढरपूर आणि बेगमपूर इथे जाऊन हिंडत मोहोळास आलो. तेथून
                  सोलापुरास आलो. तेथे काही महिने राहून अक्कलकोटास आलो आता इथेच रहाणार.’ स्वामींच्या या बोलण्याने चोळप्पा
                  भारावले.
                </p>
                <p>
                  श्री स्वामींच्या दिव्यत्वाची प्रचिती अक्कलकोट येथील मंडळींना येऊ लागली. लोक स्वामींच्या दर्शनासाठी येऊ
                  लागले. अक्कलकोटचे राजेसाहेब भोसले स्वामींचे भक्त झाले. स्वामी कधी राजवाडयात जात आणि एखादे वेळी ते
                  तिथेच चार सहा दिवस मुक्काम करीत असत.
                </p>
                <p>
                  स्वामी महाराज सिद्ध पुरुष होते. आपल्या वास्तव्यात त्यांनी अनेकविध चमत्कार केले. राजापासून रंकापर्यंत
                  अनेकांवर प्रेमाचा वर्षाव केला. त्यांच्या अंतरंगातील शिष्य बाळप्पा आणि चोळप्पा यांच्यावर त्यांनी अधिक
                  कृपा होती. अजानूबाहू भव्य कांती सतेज | नसे मानवी देह हा स्वामीराज || या ओळीतून स्वामींच्या देहयष्टीची
                  ओळख होते.
                </p>
                <p>
                  स्वामींच्या भक्तांमध्ये सर्व जातीपातीचे, बहुजन समाजाचे आणि धर्माचे लोक गोळा झाले. स्वामी कधी बालभावात
                  तर कधी अत्यंत रुद्रस्वरुपात दिसत. कधी ते गावातील मुलांबरोबर गोट्या खेळत तर कधी वटवृक्षाखाली ध्यानस्थ
                  बसत. त्यांच्या स्वभावाचा कधीच अंदाज येत नसे. त्यांनी अनेकांचा अहंकार दूर केला. अनेकांना सन्मार्गाला
                  लावले. ज्याचा जसा अधिकार त्याप्रमाणे त्याच्यावर कृपा केली. निर्भीडता, स्पष्टवक्तेपणा आणि आत्मीयता
                  यामुळे लाखो भक्तांना त्यांनी आपलेसे केले. त्यांच्या कार्यकाळात देशात इंग्रजांचा अंमल होता. इंग्रज
                  शासनाच्या जुलमी राजवटीत भरडल्या गेलेल्या जनतेच्या मनात आत्मसन्मान त्यांनी जागृत केला. त्यांच्या
                  भक्तांमध्ये हिंदूंप्रमाणेच मुसलमान, ख्रिश्चन अशा अनेक धर्माचे लोकही होते. त्यांच्याभोवती मोठा शिष्य
                  परिवार तयार झाला होता. प्रत्येक शिष्याला त्यांनी त्याच्या क्षमतेनुसार कार्य दिले आणि त्याच्या हाती
                  परंपरेची पताका दिली. स्वामींचे स्वरूप कधीच कुणाला समजले नाही. स्वामी अनाकलनीय होते. पण तरीही ते
                  सगळ्यांना आपले वाटत होते. स्वामींच्या भक्तांना स्वामी कसे आहेत यापेक्षा ते आपल्याजवळ आहेत याचा आनंद
                  जास्त होत असे.
                </p>
                <p>
                  ‘अकलसे खुदा पहचानो’ असे स्वामी नेहमी म्हणत. निष्क्रिय वागणाऱ्याला आणि चिंतन न करणाऱ्याला स्वामींच्या
                  कृपाशक्तीचा बोध होणार नाही. स्वामी अद्भुत आहेत. निर्बुद्ध आणि चंचल असणाऱ्याला स्वामींचे 'स्व'रूप आणि
                  त्यांच्या अघटित लीला कधीच कळणार नाहीत. स्वामी म्हणजे एकमेव चिरंतन सत्य आहेत. ते सर्व विश्वाचे
                  सर्वशक्तीमान असे मालक आहेत. स्वामी 'अवधूत' म्हणजे सर्वोच्च संन्यासी आहेत. परमहंस आहेत. स्वामी स्वयंभू,
                  स्वयंसिद्ध आहेत. ते अव्यक्त आहेत. ते भक्तांसाठी नाम आणि रूप घेतात. स्वामी ॐकारातील पहिला स्वर 'अ'कार,
                  म्हणजे शेषशायी विष्णू भगवान आहेत. संत तुकाराम महाराजांनी सांगितल्याप्रमाणे स्वामी ‘ऐसी कळवळ्याची जाती
                  | करी लाभेविण प्रीती ||’उत्कट प्रेमाची अनुभूती स्वामींच्या सहवासात त्यांच्या भक्तांना येत असे.
                  स्वामींना कुळ, जात, धर्म, पंथ, संप्रदाय नाही.
                </p>
                <p>
                  स्वामी म्हणजे अथांग सामर्थ्य आहे. स्वामी अतर्क्य आणि तपःसिद्ध यतिश्वर आहेत. ते अखंड आणि सर्व चराचराला
                  व्यापून आहेत. श्री स्वामी समर्थ कल्याणकारी देवतांचे स्वामी आहेत. सर्व देवता आणि ऋद्धी-सिद्धी स्वामींची
                  पूजा करतात. स्वामींना काम क्रोधादी विकार नाहीत. तसे संकल्प आणि विकल्प नाहीत. ते सर्वसाक्षी आहेत.
                  स्वामीच सर्व विश्वातील 'अर्थ', आनंद, प्रेम आणि सर्व जीवातील प्राण आणि तेज आहेत. स्वामी नित्य जागृत
                  आहेत. म्हणूनच स्वामींची सर्व देवस्थाने स्वामींच्या अस्तित्वाने जागृत आहेत. स्वामी महाराज हे अतिसूक्ष्म
                  आणि अतिविराट वटवृक्षासारखे आहेत. वटवृक्षाच्या तळी आणि मुळात (दत्तनगर मूळ मूळ) आहेत. म्हणून साध्या
                  पार्थिव दृष्टीला त्यांचे दर्शन होणे अवघड आहे. त्यांचे स्थान चंद्र सूर्य तारे यांच्या उदय आणि अस्त
                  यांच्या पलीकडचे आहे. स्वामी सर्व पापी आणि पुण्यवान जीवांचे सुहृद म्हणजेच जीवलग आहेत. जीवांच्या
                  उद्धारासाठीच त्यांनी सदेह अवतार या मृत्युलोकात घेतलेला आहे.
                </p>
                <p>
                  स्वामी प्रत्येकाच्या हृदयात असणारा अनंत परमात्मा आहेत. स्वामी स्मर्तृगामी म्हणजेच स्मरण करताच, हाक
                  मारताच भक्तासाठी अवतीर्ण होणारा साक्षात ईश्वर आहेत. स्वामी होणाऱ्या गोष्टींचे कर्तेपण स्वतःकडे घेत
                  नाही. ते निर्मोही, निरहंकारी आणि निर्विकारी 'साक्षी' आहेत. म्हणून ते म्हणायचे "मला नमस्कार करा किंवा
                  करु नका. माझे नामस्मरण, पूजा करा किंवा करू नका, मी आहेच. स्वामी 'अहंभावहीन’ आहेत. ते भक्तांवर नित्य
                  प्रसन्न असतात. त्याच्या पापवृत्तीवर आणि संकटावर ते रागावतात. त्याची देहशुद्धी आणि चित्तशुद्धी घडवून
                  आणून त्याला मोक्षप्राप्ती घडवतात.
                </p>
                <p>
                  स्वामी त्रिलोकाश्रय म्हणजेच स्वर्ग, पृथ्वी आणि पाताळ यांचे आधार आणि आश्रय आहेत. स्वामी आत्मसंभव,
                  निजरूप आणि निजानंद आहेत. स्वामींचे अस्तित्व हे जन्म, जरा, मरण याच्या पलीकडील आहे. स्वामी परमेश आहेत.
                  रागावर सुद्धा त्यांचे नियंत्रण आहे. स्वामींचा क्रोध सर्व विश्वाला परवडणारा नाही. म्हणून ते सर्वसामान्य
                  जीवांवर रागवत नाहीत. त्यांच्या दृष्प्रवृत्तीचे व्यवहार ते सहन करतात. सर्व विश्वच आपल्या हातात गोटीच्या
                  स्वरुपात धरून ठेवले आहे. तरी कोप झाल्यास सर्व विश्वाचाच संहार होईल म्हणून स्वामी रागावत नाहीत. ते
                  अपराधांना क्षमा करतात. स्वामी भावविनिर्गत आहेत, म्हणजेच मोहापासून निर्माण होणाऱ्या ममतेचा स्पर्श
                  स्वामींना नाही.
                </p>
                <p>
                  स्वामी चिदंबर आणि दिगंबर आहेत. चित् आणि दिक् हेच ज्यांचे वस्त्र आहे, असे विराटरूपी ते चिन्मय-चैतन्यरूप
                  आहेत. स्वामींची कृपा उदंड आणि त्याच्या मुखातून येणारे श्रीवचन हे अविनाशी त्रिकालबाधित सत्य आहे. स्वामी
                  म्हणतील तेच शेवटी खरे होईल. स्वामी कालांतक आहेत. सृष्टीतील उत्पत्ती, स्थिती, लय ही सर्व कर्मे स्वामीच
                  करतात. स्वामी हे विश्वातील तेज, प्रदीप्तमूर्ती आहेत. ते तेज स्वामींच्या नेत्रातून प्रगट होते, म्हणून
                  स्वामींच्या नजरेला नजर देता येत नाही. त्यांच्यापुढे कोणाचीही सत्ता नाही. स्वामी हे ‘ब्रह्मांडनायक’
                  आहेत.
                </p>
                <p>
                  महाराजांची वृत्ती फारच विलक्षण प्रकारची होती. त्यांच्या वृत्तीस कित्येक लोक पिशाचवृत्ती म्हणत.
                  स्वामींचे दैनिक आचरण हे संन्यासधर्माला अनुसरून अजिबात नव्हते. ते कधीही एकांतात जप, तप, अनुष्ठान
                  ध्यानधारणा करीत नसत. मुळात ते स्वतःहून काहीच करीत नसत. स्वामी स्वच्छंदाने जगत असत. त्यांचा दैनिक
                  कारभार दुसऱ्यांच्या हातानेच होत असे. स्वामींना स्नान दुसऱ्याने घालावे, परंतु स्नान व्हावे असे
                  त्यांच्या मनात आले तरच. मनात आले तर दिवसातून दोनदा-तीनदा ते स्नान करीत किंवा आठ दहा दिवस स्नानसुद्धा
                  करीत नसत. स्वतःच्या अंगाला केशर चंदनाची उटी लावून घेत आणि आरती करून घेत. स्वामींना जेवण दुसऱ्यांनीच
                  घालावे, परंतु त्यांना जेवणाची लहर आली तरच. ते कोणाच्याही हातून अन्न खात असत. स्वामींच्या अंगावर
                  पांघरूण दुसऱ्यांनीच घालावे, परंतु त्यांना अंगावर पांघरूण हवे आहे असे वाटले तरच. स्वामी मनाला वाटेल
                  त्या ठिकाणी जात असत. महाराजांच्या ठिकाणी सारी द्वंद्व सामावलेली दिसत. ते कधी मसणवटीत, तर कधी खासबागेत,
                  कधी महारवाड्यात तर कधी राजवाड्यात, कधी निवडुंगाच्या काट्यांवर, तर कधी पलंगावर, कधी मंदिरात, तर कधी
                  मठात यांप्रमाणे सारख्याच भावनेने वावरत असत. स्वामींची स्वारी बाहेर निघाली की, सर्व राजचिन्हांनी मंडित
                  दिसावी. छत्रचामरे, पालख्या, घोडे, गाई, म्हशी इत्यादी खिल्लारे, तंबू, कनाती, नगारे, वाजंत्री, रणवाद्ये,
                  सेवेकरी आणि यात्रेकरी लोकांच्या फलटणी, त्याचप्रमाणे पुराणिक, हरिदास, गवय्ये, कलावंतिणी, तमासगीर,
                  नाटकवाले, फुलवाले, मिठाईवाले असे सर्व प्रकारचे दुकानदार बरोबर असत. मग महाराज एखादे वेळी जंगलात का
                  वस्तीला जात ना, बरोबर हा इतका सरंजाम असणारच. ते त्यांच्या मनाचे राजे होते. त्यांच्या वागण्याबद्दल
                  कोणीही कधीही आक्षेप घेतला नाही. स्वामी इतक्या वेगाने चालत ही सोबतच्या भक्तानां धावावेच लागत असे. ते
                  बोलू लागले म्हणजे सतत काहीतरी बोलत असत. हुक्का ओढू लागले, म्हणजे एकसारखा हुक्काच ओढीत बसत. लहान
                  मुलांजवळ खेळू लागले म्हणजे एकसारखा खेळच चालावा. एखादे वेळी स्वामी रागावले, म्हणजे सात आठ दिवस ते
                  रागातच असत. स्वामी आनंदात असले म्हणजे सर्वांजवळ मधुर वाणीने बोलत. अशा या लोकोत्तर पुरुषाची खरी योग्यता
                  जाणण्यासाठी अंगी तशीच पात्रता पाहिजे. वारंवार होणाऱ्या चमत्कारांनी महाराज सर्वज्ञ आहेत आणि ते
                  सर्वशक्तिमान आहेत अशी प्रत्येक भक्ताची खात्री झाली. पण हे जरी सारे घडले तरी त्यांची खरी पारख फारच
                  थोड्यांना झाली असेल. स्वामी सगळ्यांना कळलेच नाही. अशा प्रकारची महाराजांची घटकेत वृत्ती बदलणारी
                  असल्याने त्यांची परीक्षा खऱ्या पारखी भक्तशिवाय कोणालाच होत नसे. ज्यांना स्वामी कळले त्यांच्या जीवन
                  कृतार्थ झाले.
                </p>
                <p>
                  स्वामींनी आपल्या भक्तांना वेळोवेळी जे उपदेश केले त्यापैकी काही उपदेश आजही आपल्यासारख्या सर्वसामान्य
                  माणसांच्या जीवनात बदल घडवू शकतात. त्यापैकी एक म्हणजे नामस्मरण. संतांच्या सांप्रदायिक प्रथेप्रमाणे
                  स्वामींनी नामस्मरणाला सर्वाधिक महत्व दिले. नामाला कसलीही उपाधी नाही. काळवेळ लागत नाही. लहानथोर भेद
                  नाही. अपेक्षापूर्तीच्या संकल्पाने जरी नामाची सुरूवात झाली तरी हरकत नाही. नाम आपले काम करतेच. हा नामाचा
                  प्रभाव कळत नकळत आपल्याच अंत:करणावर होतो. आपले अंतःकरण शुद्ध होते. प्रपचात कर्म आणि कर्तव्य जितके
                  महत्वाचे असते तितकेच परमार्थात नामस्मरण महत्वाचे असते.
                </p>
                <p>
                  स्वामींनी भक्तांना एक अभिवचन दिले. ‘अनन्याश्चिन्तयन्तो मां ये जनाः पर्युपासते | तेषां
                  नित्याभियुक्तानां योगक्षेमं वहाम्यहम् ||’ याचा अर्थ अनन्यभावाने माझी सेवा कर, मी तुझा योगक्षेम चालवेन.
                  आपला प्रपंच हा स्वामींचा आहे असे समजून त्याचा प्रेमाने सांभाळ करावा. प्रपंच करताना सगळ्यांनीच
                  नामस्मरणाची जोड द्यावी. प्रपंच सुखाचा होतो. स्वामी आपला योगक्षेम तर पहातातच त्याचबरोबर अनेक दुर्धर
                  प्रसंगात, संकटात-दु:खात आपली काळजी घेऊन ‘भिऊ नकोस मी तुझ्या पाठीशी आहे’ ह्या आश्वासनाची प्रचिती देतात.
                  स्वामी आपल्यावर कृपा करतात आणि आपल्याजवळच असल्याची खुणगाठ ‘नामावताराने’ देतात.
                </p>
                <p>
                  ‘वडाच्या पारंब्या तुम्ही धरून बसा’ असा विश्वास स्वामींनी आपल्या भक्तांना दिला. याचा अर्थ असा कि वड हे
                  अखंडत्वाचे प्रतीक आहे. हे झाड वाढते, मोठे होते, विस्तारते. त्याला अनेक पारंब्या फुटतात. त्या पुन्हा
                  जमिनीत रुजतात. त्याचा पुन्हा वृक्ष होतो. ही अखंडत्वाची खूण श्री स्वामींनी सांगितली असावी. सद्गुरूंकडून
                  नामोपदेश मिळून संजीवन नामाचे बीज साधकाच्या अंत:करणात रुजते. नामस्मरणाच्या सातत्याने ते वाढते आणि
                  विस्तारते.
                </p>
                <p>
                  स्वामी सेवा करणाऱ्या भक्तांना आजही मनात अशी शंका येते कि, आपण स्वामींची इतकी सेवा केली, तरी स्वामी
                  अजून का प्रसन्न होत नाहीत? अजून त्यांची कृपादृष्टी का होत नाही? ह्याला कारण आपला मागील जन्म आपल्याला
                  ज्ञात नाही. दु:ख आणि संकटे एकामागून एक येतच राहिली तर मन चलबिचल होते. आपल्याच वाट्याला एवढी दु:खे का?
                  इतके नामस्मरण केले, तरी स्वामींना आपली दया का येत नाही? निराशेने नामस्मरण सोडून देण्याचे विचारही मनात
                  येऊ लागतात. पण स्वामी भक्तांनी अशा विकल्पांना अजिबात थारा देऊ नये. त्यांनी नामाला धरून राहावे. कारण
                  हीच आपल्या परीक्षेची वेळ असते. आपला भक्त प्रारब्ध भोगातून मुक्त व्हावा हीच स्वामींची इच्छा असते.
                  स्वामी खूप दयाळू आहेत. दुःखात आणि संकटात ते आपल्याला आशेचा मार्ग दाखवतात. अशा वेळी स्वामी नामरूपाने
                  सदैव आपल्या सोबत राहून अडचणींच्या काळात आपला मार्ग सुखकर करतात. म्हणूनच नामाला कधीच सोडू नये. कारण
                  आपले पूर्वसंचित संपल्याशिवाय आपली साधना फळाला येत नाही. दु:ख-संकटे असतील तरच आपल्याला सुखाची किंमत
                  कळते आणि भगवंताच्या अस्तित्वाची जाणीवही ह्या एकाच गोष्टीमुळे आपल्याला होत राहते. आपल्याला जे काही
                  मिळते ते केवळ स्वामीकृपेमुळेच हा विश्वास आपल्याला सतत जाणवला पाहिजे. स्वामीकृपेशिवाय मला काहीच नको ही
                  एकच भावना आपल्याला अंत:करणात खोलवर रुजवावी लागते. कारण तीच एकमेव शाश्वत विसाव्याची जागा आहे. बाकी सर्व
                  अशाश्वत आणि दु:खदायक आहे. यासाठी स्वामी मला फक्त तुम्ही हवे आहात अशी तळमळ जीवला लागली तरच स्वामींच्या
                  अस्तित्वाची प्रचिती येते. स्वामी म्हणजे साक्षात कृपासिंधूच. त्यासाठी स्वामींवर आपली अढळ निष्ठा हवी.
                </p>
                <p>
                  सर्वसाधारणपणे स्वामींचा दिनक्रम ठरलेला असे. भल्या पहाटे भक्त मंडळी स्वामींना स्नान घालीत. नंतर संध्या
                  वगैरे. श्री स्वामी समर्थ फक्त दोन आचमने घेत. नंतर त्यांना लंगोटी नेसवावी लागे. थोडासा फराळ घेऊन ते
                  भक्तांसमोर येत आणि दर्शन देत असत. स्वामी सर्व भक्तांच्या मनातील कामना ओळखून त्यांच्या इच्छा पूर्ण
                  करीत. स्वामींची कीर्ती सर्व भारतभर पसरली. बडोदे, इंदोर, ग्वाल्हेर येथील संस्थानिक अक्कलकोट येथे
                  दर्शनास येत. नाना धर्माचे अशिक्षित, सुशिक्षित लोक स्वामींच्या दर्शनाला अक्कलकोटला येऊ लागले. यातील
                  काही जिज्ञासू, अतिथी असत तर काही कुटाळक्या करणारे आणि स्वामींची परीक्षा पहाणारेही येत. स्वामी
                  प्रत्येकाला त्याचे अचूक उत्तर देत. निरनिराळ्या भाविक लोकांबरोबर स्वामी त्यांचे भाषेत बोलत आणि
                  जिज्ञासूंचे समाधान करीत.
                </p>
                <p>
                  सोमनाथापासून जगन्नाथापर्यंत आणि विश्वेश्वरापासून रामेश्वरापर्यंत अक्षरश: अगणित भक्त स्वामींच्या
                  दर्शनाला येत असत. शास्त्रसंपन्न पंडितांपासून अक्षरशत्रू बसाप्पापर्यंत, राजाधिराजापासून
                  भाग्यहीनापर्यंत, वेदशास्त्रसंपन्न ब्राह्मणापासून अंत्यजापर्यंत, सात्विक सदाचारसंपन्न सतीपासून ते
                  दुराचारी गणिकांपर्यंत प्रतिदिनी असंख्य भक्त स्वामींकडे येत. कोणी शुद्धभावनेने, कोणी निष्काम सेवेसाठी,
                  कोणी कामनापूर्तीसाठी, कोणी परीक्षा पाहण्यासाठी वा निंदानालस्ती करण्यासाठी. स्वामींनी आलेल्या
                  व्यक्तींचा कधीही कंटाळा केला नाही. उलट सान्निध्यात आलेल्या प्रत्येकास आयुष्यभर जतन करावा वाटेल असा
                  अनुभवाचा अमोल ठेवा दिला. आस्तिकांपासून नास्तिकांपर्यंत सर्व प्रकारच्या भक्तांना ईश्वरसेवेकडे वळविले.
                </p>
                <p>एरव्ही लक्षावधी लोक स्वामींच्या दर्शनास येत असत. हिंदुस्थानाच्या चारी टोकांकडील आणि साऱ्या धर्मांतील
                  लोक स्वामींच्या दर्शनास येत. शिंदे, होळकर, गायकवाड, भोसले असे संस्थानिक त्यांच्या भजनी होते. युरोपियन
                  बंडगार्डन, पारशी नवरोजी शेट, मुसलमान सय्यद आणि अहमदअल्ली रिसालदार, त्याचप्रमाणे जैन, लिंगायत, वैष्णव,
                  वारकरी, संन्यासी, सुधारक, सनातनी, शास्त्री, हरिदास असे अनेक जण स्वामींच्या भक्तीत रंगले.
                </p>
                <p>
                  स्वामींनी अक्कलकोटला २१ वर्षे वास्तव्य केले. स्वामी वटवृक्षाखाली नेहमी बसत. या वटवृक्षाखाली शके १८००
                  बहुधान्य नाम संवत्सर चैत्र कृ. त्रयोदशी या दिवशी स्वामींनी लौकिक दृष्ट्या निजानंदी निमग्न झाले.
                  स्वामींनी देह ठेवण्यापूर्वी एक वर्ष आधी आपल्या अवतार समाप्तीची सूचना भक्तांना दिली होती.
                  अवतारसमाप्तीच्या आधी आठ दिवस त्यांनी ‘अखंड नाम-भजन’ सुरू ठेवले. या दिवसात त्यांना ताप आला. त्यांनी
                  अन्नत्यागही केला. चैत्र वद्य त्रयोदशी या दिवशी स्वामींनी मंगलस्नान करून ध्यानमग्न झाले. त्यावेळी
                  भक्तांनी त्यांना विचारले की, आपण बरे केव्हा व्हाल? तेव्हा स्वामी म्हणाले, “जेव्हा पंढरी जळेल अथवा
                  डोंगर बोलतील तेव्हाच मला आराम पडेल. त्यासाठी तुम्ही दुःखी का होता?” याचा अर्थ असा कि स्वामींच्या देह
                  समाप्तीनंतर त्यांचे विश्वकल्याणाचे कार्य अनेक वर्षे चालू राहणार आहे.
                </p>
                <p>
                  स्वामी महाराजांची शिष्य परंपरा खूप मोठी आहे. त्यांच्या प्रमुख शिष्यांमध्ये बाळप्पा, चोळप्पा आणि
                  सुंदराबाई यांच्या समवेत कोल्हापूरचे कुंभार स्वामी, पुण्याचे बिडकर महाराज, मुंबईचे तात महाराज, आळंदीचे
                  नृसिंहसरस्वती, शंकरमहाराज, वामनबुवा, गुलाबराव महाराज, केळकरबुवा, स्वामीसुत, आनंदभारती, गजानन महाराज
                  (शेगाव), आनंदनाथ महाराज, मंगळवेढ्याचे बाळकृष्णबोवा आणि देवमामलेदार हे आणि असे अनेक भक्त त्यांच्या
                  अंतरंग शिष्य परंपरेतील होते. या शिष्यांनी महाराष्ट्रात मुंबई, पुणे, चिपळूण, गोवा, वेंगुर्ला या आणि
                  अश्या विविध ठिकाणी तसेच गुजरातेत बडोदा, सुरत, अहमदाबाद आदी ठिकाणी श्री स्वामी समर्थाचे मठ स्थापन केले
                  आहेत.
                </p>
