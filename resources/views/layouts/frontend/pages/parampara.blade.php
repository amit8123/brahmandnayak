                  दर्शनासाठी वाडीस नियमाने जात आणि दोन दिवस राहून परत गावी येत. त्यांना कशाचीही कमतरता नव्हती. परंतु घरी
                  संतान नसल्यामुळे अन्नपूर्णेला घर ओस वाटत असे. त्यामुळे तिने एकदा पतीस सांगितले की, “‘आपल्या घरात
                  पैसा-अडका आणि धनधान्य मुबलक असले तरी आपल्याला संतान नसल्यामुळे ते सर्व काही व्यर्थ आहे. तरी
                  श्रीदत्तचरणी प्रार्थना करुन माझी इच्छा पुरी करावी. तेव्हा शनिवारी त्या भक्तकैवारी दत्त महाराजांना
                  प्रार्थना करा. तो आपल्याला निश्चित पुत्र देईल. आपल्या संसारात सुख आणि आनंद निर्माण करील”. परंतु त्या
                  अप्पाभटाने तिचे बोलणे मनावर घेतले नाही.
                </p>
                <p>
                  या गोष्टीला बरेच दिवस लोटले. एके दिवशी वाडीस गेला असताना दर्शनाच्या वेळी अप्पाभटाने आपल्या पत्नीची
                  इच्छा दत्त महाराजांच्या चरणी ठेवली. यथाविधी पूजा, आरती आणि प्रार्थना झाल्यावर भोजन करून ते झोपले. त्या
                  रात्री त्यांना स्वप्नात एक साधूपुरुष दिसला. तो म्हणाला, ‘‘हे ब्राह्मणा, उगाच काळजी करू नकोस. निश्चिंत
                  राहा. मी स्वत:च तुझा पुत्र म्हणून तुझ्या घरी येईन.’’ ते स्वप्न पाहून तो ब्राह्मण जागा झाला. दुसऱ्या
                  दिवशी आपल्या गावी घरी जाताच त्याने पत्नीला पाहिलेला स्वप्न दृष्टांत सांगितला. ते ऐकून अन्नपूर्णेला
                  आनंद झाला. या गोष्टीला तीन महिने उलटून गेले. अन्नपूर्णेला दिवस राहिले. मारुतीचे दर्शन घ्यावे आणि
                  देवळात बसून राहावे असे वाटू लागले. अशा प्रकारच्या डोहाळ्यामुळे अन्नपूर्णेला खूप आनंद झाला प्रसूतीचा
                  दिवस जवळ आला. शके १७५७ माघ कृष्ण पंचमी रविवार प्रात:काळी अन्नपूर्णा प्रसूत होऊन तिला मुलगा झाला.
                  प्रत्यक्ष भगवंताचा अवतार जन्माला आल्याने मातेला प्रसूतीच्या वेदना जाणवल्या नाहीत. कलियुगी
                  पुराण-पुरुषाने मानवावतार घेतला. त्याचे नाव श्रीकृष्ण ठेवण्यात आले.
                </p>
                <p>
                  श्रीकृष्ण आता मोठा झाला. एकदा आपल्या आईच्या सांगण्यावरून कुलदेवतेच्या दर्शनासाठी मंगसोळीला पोहचला.
                  कुलदेवतेचे दर्शन होताच त्याने साष्टांग नमस्कार केला. देवाचे स्तुतिस्तोत्र गायिले आणि देवाला प्रार्थना
                  केली, ‘‘तुझ्या दर्शनासाठी मी इथे आलो आहे. तू माझा स्वामी आणि मी तुझा दास आहे. जोपर्यंत तू मला साक्षात
                  दर्शन देत नाहीस तोपर्यंत मी अन्नत्याग करून लिंबाच्या झाडाखाली बसून राहणार.” छोट्या श्रीकृष्णाची
                  दर्शनाची तळमळ पाहून कुलदेव त्याच्यासमोर ब्राह्मणरूपाने आले. ब्राह्मणाला पाहताच नकळत श्रीकृष्णाचे हात
                  जोडले गेले. ब्राह्मणाच्या जागी पार्वतीसह भगवान शंकर प्रगट झाले. भगवान त्याला म्हणाले, "श्रीकृष्णा, अरे
                  तू माझाच अवतार आहेस. मग माझ्या दर्शासाठी हट्ट का केलास? तुझ्यात माझाच अंश आहे. गरीबांचा उद्धार
                  करण्यासाठी तू हा अवतार घेतला आहेस हे लक्षात ठेव." असे म्हणून त्याला आशीर्वाद दिला. भगवान शंकर म्हणाले,
                  "आधी अक्कलकोटला जा. तिथे नृसिंहभान नावाचे प्रसिद्ध स्वामी आहेत. ते भक्तासाठी वारंवार त्रैमूर्ती देह
                  धारण करतात. तरी बुद्धी स्थिर करुन गुरुमहती वाढवावी.’’ असे सांगून भगवान अदृश्य झाले. श्रीकृष्ण म्हणजे
                  साक्षात त्रिमूर्तीचा अंश. प्रत्यक्ष त्र्यंबकेश्वरच्या आशीर्वादाने त्याची देहबुद्धी तेजस्वी झाली. मनाशी
                  निश्चित असा निर्णय करून श्रीकृष्ण घरी आला. घरी येताच त्याने घडलेला सगळा प्रकार सांगितला आणि
                  आईवडिलांच्या परवानगीने श्रीकृष्ण अक्कलकोटला निघाला. भगवंताने सांगितल्याप्रमाणे अक्कलकोटला असलेल्या
                  श्री गुरूंना भेटण्याचा प्रचंड ध्यास त्याच्या मनात होता. गुरूंना भेटायच्या ओढीने तो अक्कलकोटला पोहचला.
                </p>
                <p>
                  गावातील लोकांना विचारीत तो स्वामींपर्यंत पोहचला. सूर्यप्रकाशासारखी स्वामींची तेजस्वी मूर्ती पाहून
                  श्रीकृष्णाला आनंद झाला. त्याने धावत जाऊन स्वामींच्या पायावर लोटांगण घातले. बालवयातच कुलदेवाच्या
                  आज्ञेने कृष्णा अक्कलकोटला स्वामी समर्थांकडे आला होता. ‘माझा कृष्णा येणार’ म्हणून स्वामी समर्थ
                  सकाळपासून कृष्णाची वाट पहात होते. पायावर लोटांगण घातलेल्या श्रीकृष्णाला उचलून स्वामींनी जवळ घेतले.
                  स्वामी म्हणाले, "तू आणि मी एकच आहोत. आजपासून तुला मी गुरुकृष्ण म्हणून हाक मारणार.’ स्वामी ताबडतोब
                  गुरुकृष्णाला घेऊन रानात एकांतात गेले. तिथे दोघेही तीन दिवस राहिले आणि अक्कलकोटला परत आले.
                </p>
                <p>
                  गुरुकृष्णाच्या भक्तीने आणि सेवेमुळे स्वामी आनंदित झाले. स्वामी म्हणाले, "‘हे सारे पुरे कर. सांगतो तो
                  ऐक. कसला गुरु व कसला सेवक? अवघा एकच विचार कर की, जगाचा उद्धार करण्यासाठी तुला अवतार घ्यावा लागला आहे.
                  नितीनियमांची मर्यादा न ओलांडता तुला जगात संचार करावयाचा आहे. तेव्हां तू आता करवीरक्षेत्री जा आणि
                  तुझ्या अवताराचे कार्य साधून घे. जे भक्त पुण्यभावाने भक्ती करतील त्यांचे कल्याण कर.’’ एवढे बोलून आपला
                  कृपेचा हात स्वामींनी गुरुकृष्णांच्या मस्तकी ठेवला. गुरु-शिष्याच्या या आशीर्वाद सोहळ्यात दोघांचेही
                  देहभान हरपले. स्वामींनी गुरुकृष्णाला श्री गुरु कृष्णसरस्वती या नावाने गौरविले.
                </p>
                <p>
                  श्री गुरु कृष्णसरस्वतींना स्वामींच्या सहवासात राहायचे होते. त्यामुळे त्याने करवीरला जाण्याचा प्रयत्न
                  केला नाही. शेवटी सात दिवसानंतर स्वामी श्री गुरु कृष्णसरस्वतींच्या पाठीवर हात फिरवून म्हणाले, “बाळा,
                  सावध हो. तुला अजून खूप कार्य करावयाचे आहे. आता तुला करवीर नगरीत जायचे आहे.” स्वामींना साष्टांग नमस्कार
                  करुन श्री गुरु कृष्णसरस्वती म्हणाले, ‘‘तुमची आज्ञा प्रमाण’’. स्वामींनी श्री गुरु कृष्णसरस्वतींना
                  कोल्हापूरला जाण्याची आज्ञा दिली. दुसरे दिवशी श्री गुरु कृष्णसरस्वती कोल्हापूरला जायला निघाले. दोन
                  दिवसानंतर ते कोल्हापूरला पोहचले आणि तिथल्या राममंदिरात वस्ती केली.
                </p>
                <p>
                  ताराबाई शिर्के ही कोल्हापूर येथील कुंभार आळीतील एक गणिका होती. तिला पोटशूळाचा त्रास होता. श्री
                  दत्तगुरुंवर तिची खूप श्रद्धा होती. ती नित्य नियमाने नृसिंहवाडीची पौर्णिमा वारी करीत असे. तिच्या ह्या
                  अनेक वर्षाच्या एकनिष्ठ सेवेचे फळ म्हणून दत्तगुरूंनी तिला स्वप्न दृष्टांत दिला. स्वप्नात दत्तमहाराज
                  म्हणाले, “मी तुझ्यावर प्रसन्न आहे. काही दिवसात मी तुझ्या घरी रहायला येईन. तुला कशाची चिंता आहे? आज
                  तुझी व्यथा संपली. आता येथे येऊ नको. घरीच श्रीगुरुकृष्णाला आणून त्याच्या सेवेत एकनिष्ठ रहा. तू गेल्यास
                  तुला तेथे श्री गुरु कृष्णसरस्वती भेटतील. त्यांना घेऊन घरी ये.” ताराबाई जागी झाली. सकाळीच उठून ताराबाई
                  महिसाळ गावी गेली. सोबत घोड्याचा रथ घेतला. श्री गुरु कृष्णसरस्वती ज्या ठिकाणी रहात होते त्याची चौकशी
                  करीत ताराबाई रथासह तिथे पोहचली. गुरुमाऊलीला साष्टांग वंदन केले आणि म्हणाली, ‘‘हे करुणाघन गुरुराया,
                  माझ्याजवळ माझे गुरु असतानाही मी नको तिथे फिरत होते. मी किती हीन स्त्री आहे. कसल्या मायेला भुलले होते
                  कोण जाणे. मी तुम्हांला ओळखले नाही. माझ्यावर कृपा करा आणि माझ्या घरी चला.” तिचा हात धरुन श्री गुरु
                  कृष्णसरस्वती म्हणाले, “रथ तयार कर” ते ऐकून ताराबाईला फार आनंद झाला आणि म्हणाली, “स्वामी, आज मी धन्य
                  झाले”.
                </p>
                <p>
                  श्री गुरु कृष्णसरस्वती महाराज कोल्हापूरला कुंभार आळीतील ताराबाई शिर्के यांच्या वाड्यात राहू लागले. या
                  आळीत बऱ्याच प्रमाणावर गणिकांची (वेश्या) वस्ती होती. पण स्वामींच्या वास्तव्याने सर्व वस्ती पावन झाली.
                  महाराज वाड्यावर रहायला आल्यापासून ताराबाईंनी स्वतःला स्वामी सेवेत झोकून दिले. ताराबाईंनी स्वामींची
                  मनोभावे सेवा सुरु केली. रोज काकड आरती, नैवेद्य आरती, धुपारती, शेजारती असा पूजेचा दिनक्रम ठरून गेला.
                  जेवण झाल्यावर त्या महाराजानां सुवासिक विडाही अर्पण करीत.
                </p>
                <p>
                  गणिकेच्या ठिकाणी उत्पन्न होणारे वासनादि षडरिपु आता केव्हांच गाळून पडले. ज्या वाड्यात घुंगरांचा आणि
                  गाण्यांचा आवाज यायचा, त्या वाड्यातून आता भजनाचे आणि आरतीचे सूर ऐकू येऊ लागले. ताराबाईच्या वाड्याला एका
                  अर्थी वैराग्य प्राप्त झाले. म्हणून महाराजांच्या वास्तव्याने पावन झालेला हा वाडा आता वैराग्यमठी नावाने
                  ओळखला जाऊ लागला. महाराज या वैराग्य मठीत २५ ते ३० वर्षे राहिले.
                </p>
                <p>
                  स्वामीजी अखंड बालभावात रहात असत. स्वामींच्या अनेक साधकांना गाणगापूर, नृसिंहवाडी, औदुंबर येथे तप करीत
                  असता ‘मी करवीर येथे, कुंभार स्वामी या नावाने अवतार घेतला आहे. तेथे जावे’ असे स्वप्नदृष्टांत झाले. पण
                  कित्येक वेळा भक्तांना नृसिंहवाडीस स्वामींची भेट होत असे.
                </p>
                <p>
                  महाराजांची स्वारी या वैराग्य मठीत असताना अनेक भक्तगण दर्शनाला येत असत. बराच काळ लोटला. मध्यंतरीच्या
                  काळात काहींना महाराजांचे या वेश्यावस्तीमधील घरात राहणे आवडत नव्हते. त्यांनी महाराजाना कोल्हापुरात
                  दुसऱ्या एखाद्या ठिकाणी नेण्याचा प्रयत्न केला. पण त्यात त्या भक्तांना अपयश आले. या भक्तांना महाराजांनी
                  दृष्टांत देऊन सांगितले की, “ताराबाईंनी श्रीहनुमानाची फार भक्ती केली आहे. ताराबाईंच्या भक्तीने
                  श्रीहनुमान जखडला गेला आहे आणि मी हनुमानाचा अंश असल्याने येथे राहून तिच्या भक्तीच्या रुपयातील पंचवीस
                  पैशाचे देणे भागवता येत नाही.” या दृष्टांतामुळे त्या भक्तांनी जो बोध घ्यायचा तो घेतला. पुन्हा
                  महाराजांना कुंभारगल्लीतील ताराबाईंच्या वाड्यातून दुसरीकडे नेण्याचा प्रयत्न पुन्हा झाला नाही. त्यानंतर
                  मात्र महाराज कधीही कोल्हापूर सोडून कुठेही गेले नाहीत. महाराजांचे वास्तव्य या वाड्यात असतानाच्या काळात
                  अनेक भक्त त्यांची सेवा करण्याचा आनंद घेत असत.
                </p>
                <p>
                  श्री गुरु कृष्णसरस्वती महाराजांचा शिष्य परिवार फार मोठा होता. कृष्णा लाड, ऐतवड्याचे देवगोंडा, कागलचे
                  हरिपंत, मिरजेचे मल्लभट जोशी, सिदनेर्लीकर, वासुदेव दळवी, दादा पंडित, व्यास शास्त्री, रामभाऊ पुजारी,
                  महादेवभट, अनंत आळतेकर, बाळकृष्ण राशिवडेकर, रांगोळी महाराज, नामदेव महाराज वगैरे बरीच मंडळी महाराजांच्या
                  अंतरंग शिष्यांपैकी होती.
                </p>
                <p>
                  इ.स. १९०० चा श्रावण महिना होता. श्रवणसरींचा खेळ सुरु होता. दरवर्षीप्रमाणे श्रावण कृष्ण अष्टमीच्या
                  कृष्ण जन्माच्या सोहळ्याची तयारी वैराग्य मठीत सुरु होती. सकाळपासून भजन, कीर्तन नामस्मरण यांच्या आवाजाने
                  मठीत आनंदी आनंद होता. पण या आनंदावर दुःखाची सावली होती याची कुणालाच कल्पना नव्हती.
                </p>
                <p>
                  श्री गुरु कृष्णसरस्वतींची प्रकृती ठीक नसतानाही कृष्णजन्माच्या भजन-कीर्तनासाठी थोडा वेळ आपल्या
                  सिंहासनावर येऊन बसले. श्रीकृष्णजन्माचे भजन सुरु होते. भगवान् श्रीकृष्णांच्या जन्माची वेळ जवळ येऊ
                  लागताच सर्वांना गुलाल-फुले उधळण्यासाठी वाटण्यात आली. परंतु कृष्णजन्माच्या वेळेपूर्वीच स्वामींनी
                  गुलाल-फुले उधळून दिली आणि ते आपल्या खोलीत पलंगावर जाऊन निजले. स्वामींच्या अंतरंगातील शिष्यांच्या मनात
                  शंकेची पाल चुकचुकली, 'हे काय विपरीत'. स्वामींच्या या कृतीमुळे सगळेच शिष्य स्वामींच्या भोवतीच होते.
                  दिवस रात्र भक्त मंडळी सोबतच राहू लागली. स्वामींचा परमभक्त नामदेव गाणगापूर क्षेत्री होता. तिकडे
                  त्याच्या स्वप्नामध्ये स्वामींनी जाऊन त्यांस अगदी लवकरात लवकर वैराग्य मठीत येण्यास सांगितले. त्या
                  आज्ञेनुसार नामदेवांनी निर्गुण पादुकांचे दर्शन घेतले आणि स्वामी भेटीच्या ओढीने थेट कोल्हापूर गाठले.
                  कुंभारगल्लीतील वैराग्य मठीत येताच त्याने स्वामींचे दर्शन घेताच त्यांचे समाधान झाले. कृष्णजन्माच्या
                  वेळी झालेला सगळा प्रकार समजताच नामदेवांना दृष्टांताचा अर्थ समजला. अहोरात्र स्वामींच्या सोबत राहून
                  थकलेल्या भक्तांनी त्या दिवशी नामदेवालाच रात्री स्वामींच्या जवळ बसण्यास सांगितले. नामदेवाने आनंदाने ही
                  सेवा कबूल केली. स्वामींच्या शेजारी बसून नामदेव नामस्मरण करू लागला. दोन दिवसांच्या जागरणाने इतर भक्त
                  गाढ झोपले होते.
                </p>
                <p>
                  मठीत स्वामी आणि नामदेव दोघेच जागे होते. मध्यरात्रही उलटून गेली. शके १८२२ श्रावण वद्य दशमीच्या
                  ब्राह्ममुहुर्ताला पहाटे करवीरातील जगतजननी श्रीमहालक्ष्मी अंबाबाईच्या मंदिरातील काकड आरतीचा घंटानाद ऐकू
                  आला. त्याच वेळी हलक्या आवाजात स्वामींनी शेजारी बसलेल्या नामदेवांना बोलावून कापूर लावून स्वतःस त्यांनी
                  त्या कापूर आरतीने ओवाळून लावण्याची आज्ञा केली. स्वतःला कापूर आरतीने ओवाळून घेतले. आरतीमधील कापूराची
                  ज्योत अधिक तेजोमय झाली आणि या ज्योतीमध्येच सगुण रूपातील श्री गुरु कृष्णसरस्वतींची ज्योत एकरूप झाली.
                  स्वामींच्या निश्चल देहाकडे पाहत नामदेवाने करुण अंतःकरणाने हंबरडा फोडला. नामदेवाचा हंबरडा ऐकून सर्व
                  भक्तजन झोपलेले सगळे भक्त धावतच स्वामींच्या खोलीजवळ आले. सगळ्यांना हवा असलेला आधार त्यांना निराधार करून
                  गेला. सगळ्यांना अश्रू आवरेनासे झाले. कोणाचे आणि कसे सांत्वन करायचे हेच कळत नव्हते. वैराग्य मठीतील ही
                  बातमी वाऱ्याच्या वेगाने करवीर नगरीत पसरली. भक्तांची पाऊले स्वामींच्या शेवटच्या दर्शनासाठी मठीकडे चालू
                  लागली. आलेला प्रत्येक लहान-थोर, स्त्री-पुरूष आपण पोरके झालो या भावनेने अश्रू गाळू लागला.
                </p>
                <p>
                  सद्भक्त ताराबाईला दिलेल्या वचनानुसार स्वामींनी आपल्या समाधीसाठी कुंभार गल्लीतील ताराबाईच्या वाड्यात
                  म्हणजेच वैराग्य मठीत पुढील व्यवस्था करण्याची प्रेरणा सर्व भक्तजनांना दिली. त्यावेळचे कोल्हापूरचे राजे
                  श्रीमंत छत्रपती शाहू महाराज यांनीही स्वामींचा महिमा जाणून सर्व स्वामींच्या इच्छेनुसार वैराग्य मठीत
                  समाधी देण्याची परवानगी दिली. पूर्व नियोजित स्थळी भूगर्भामध्ये परमपूज्य स्वामींचा पवित्र देह यथावकाश
                  व्यवस्थित जागा करुन पद्मासनस्थ केला. वेदमंत्रांच्या घोषात आणि नाम-संकीर्तनाच्या गजरात अत्यंत
                  श्रद्धापूर्वक स्वामींची अखेरची पूजा केली गेली. स्वामींच्या पावन देहाभोवती मीठ-कापूर भरून तो समाधिस्त
                  करण्यात आला. समाधीसाठी वापरण्यात आलेला पाषाण हा श्री क्षेत्र ज्योतिबा डोंगराचा असून त्याला चंद्रमौळी
                  पाषाण असे म्हटले जाते. त्यावर ‘श्रीं’ची प्रतिमा सर्व विधीयुक्त पूजा करून स्थापन करण्यात आली.
                  भजन-पूजन-अन्नदानादि सारे कार्य यथासांग संपन्न झाले. स्वामींनी पूर्वी दिलेल्या स्पष्ट संकेतानुसार
                  स्वामी देहाने नसूनही त्यांच्या अस्तित्वाची प्रचिती भक्तांना येऊ लागली. विरह दुःखाने व्याकुळ झालेल्या
                  भक्तांना त्यांच्या असण्याचा अनुभव वेळोवेळी विविध घटनांतून येऊ लागला. त्यामुळे आजही स्वामींचे भक्त
                  पुन्हा भक्तीत रंगून त्यांचे नामस्मरण करतात.
                </p>
                <p>
                  श्री गुरु कृष्णसरस्वती महाराजांचे संपूर्ण चरित्र ‘श्री कृष्ण विजय’ या नावाने कोल्हापूरातील महाराजांचे
                  शिष्य नारायण मुजुमदार यांनी २ भागात लिहिले आहे.
                </p>
                <p>
                  श्री गुरु कृष्णसरस्वतींची ज्ञात गुरुपरंपरा (श्रद्धाकल्पना) <br>
                  श्री दत्तात्रेय - श्री स्वामी समर्थ - श्री गुरु कृष्णसरस्वती - नामदेव महाराज - कै नाना परांजपे
                  (लोणावळा).
                </p>
