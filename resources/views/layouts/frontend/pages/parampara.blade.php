                  त्याची कामना गुरु पूर्ण करतोच.' स्वामी बाळप्पाना हाच धडा देतात.
                </p>
                <p>
                  एकदा बाळप्पा स्वामींना प्रसन्नचित्ताने नमस्कार करीत असताना
                  स्वामींनी आपली तुळशीची प्रासादिक माळ त्यांचा गळ्यात घातली आणि
                  'यात्रा झाली कारे' असा त्रिवार उच्चार केला. स्वामींनी माळेद्वारे
                  आपल्या तप:सामार्थ्याचा वारसाच बाळप्पाना दिला.
                </p>
                <p>
                  स्वामींचा निर्वाण काळ जवळ आला असता स्वामींनी आपल्या हातातील,
                  "श्री स्वामी समर्थ" अक्षरे कोरलेली अंगठी बाळप्पाच्या बोटात
                  घातली. जणू माझा शिक्का तू चालव असा अशीर्वादच दिला. स्वामींनी
                  आपल्या कंठातील रुद्राक्ष, छाटी, हातात निशाण दिले. प्रसाद पादुका
                  दिल्या आणि मस्तकावर वरदहस्त ठेवला. शेवटी स्वामी म्हणाले औदुंबर
                  छायेत बस. स्वामींचे अवतार कार्य बाळप्पा कडे आले. मठ हीं बांधून
                  झाला. बाळप्पानी ‘श्री स्वामी समर्थ ब्रह्मानंद स्वामी महाराज’ हे
                  नाव धारण करून चातुर्थाश्रम स्वीकारला.
                </p>
                <p>
                  स्वामींच्या चरणी मिळालेल्या मौल्यवान गोष्टी आणि भंडारगृहाची
                  जबाबदारी बाळप्पाकडे होती. ती जबाबदारी ते अत्यंत काटेकोरपणे
                  संभाळीत होते. स्वामींना हव्या त्या गोष्टी ताबडतोब पुरवण्याचे काम
                  ते अत्यंत तत्परतेने आणि प्रामाणिकपणे करीत. बाळप्पांना मिळालेल्या
                  जबाबदारीने सुंदराबाईंचा मत्सर वाढला. पण बाळप्पा स्वामींचे
                  एकनिष्ठ सेवक. ते कशाला इतरांची चिंता करणार. स्वामींनी आपल्या
                  सहवासात आपल्या ह्या एकनिष्ठ भक्ताला गुरू म्हणजेच सर्वव्यापी
                  परमेश्र्वराचे एक स्वरूप असल्याचे पटवून दिले. त्यांनी बाळप्पाच्या
                  कठीण परीक्षा घेतल्या. एके दिवशी बाळप्पा स्नान करून आल्यावर
                  त्यांनी एका क्षुद्राकडून पाणी आणण्यास सांगितले. बाळप्पा नाखूश
                  होते. परमेश्र्वराला सर्व माणसे समानच आहेत आणि तो त्यांच्यात
                  भेदभाव कधीही करीत नाही हे आपल्या कृतीतून स्वामींनी एकनिष्ठ सेवा
                  करणाऱ्या बाळप्पाला पटवून दिले.
                </p>
                <p>
                  श्री स्वामी समर्थांच्या सेवेत अनेक सेवेकरी होते. ते
                  त्यांच्यापरीने सेवा करीत. पण यात थोर असलेले बाळप्पा
                  यांच्याबद्द्लचा हा प्रसंग. बाळप्पानी स्वामीसेवेची नीटनेटकी
                  व्यवस्था ठेवली होती. किंबहुना असे म्हणु की स्वामींची सेवा कशी
                  करावी याचाच परिपाठ त्यांनी सर्वांना घालुन दिला जो आजही कार्यरत
                  आहे.
                </p>
                <p>
                  रोज सकाळी भुपाळीने सुरवात करुन स्नान वगैरेची जी सेवा असायची यात
                  बाळप्पा, भुजंगा, चोळाप्पाचे जावाई श्रीपाद स्वामी, सुंदराबाई असे
                  चार जण आणि इतर काही भक्तगण असायचे. प्रत्येकाची कामे ठरलेली असत.
                  एकमेकांच्या कामात कुणीही अजिबात ढवळाढवळ करायची नाही असा नियम
                  असायचा. नियमाप्रमाणे रोज आरती व्हायचीच मग स्वामी कोठेही असोत.
                  यात खंड पडला नाही. आरती झाली की मग भक्तांनी समर्पित केलेला जो
                  काही नैवेद्य असेल तो मात्र स्वामी स्वहस्ते वाटायचे. हेतु हा की
                  सर्वांना स्वामींचे दर्शन मिळावे.
                </p>
                <p>
                  हा प्रसाद वाटत असताना बाळप्पा नेहमी प्रसादाकरीता हात पुढे करीत.
                  पण स्वामींनी कधीही बाळप्पाला प्रसाद दिला नाही. बाळप्पा रोज मनात
                  खट्टू होऊन त्यांच्या घरी परत येत असत. आजही स्वामींनी आपणास
                  प्रसाद मिळाला नाही म्हणून रोज रडत बसत. अशी बरीच वर्षे गेली. रोज
                  बाळप्पा हात पुढे करीत आणि स्वामी त्यांना काहीही देत नसत. एक दिवस
                  मात्र बाळप्पानीं ठरवले की काहीही होवो आज प्रसाद घेतल्याशिवाय घरी
                  जायचेच नाही. स्वामींची आरती झाली. दर्शन आणि प्रसाद घेण्याकरीता
                  नेहेमीप्रमाणे भक्तगण स्वामींच्या भोवती गोलाकार उभे राहिले.
                  स्वामी सर्वांना प्रसाद देऊ लागले. बाळप्पानी काय केले असावे? एक
                  भक्ताच्या दोन पाया मधुन हात घातला अन प्रसादाची वाट पाहू लागले
                  हेतु हा की मी स्वामींना दिसू नये. वास्तविक स्वामीच या सृष्टीचे
                  चालक-पालक-मालक आहेत. मग अशी कोणती गोष्ट आहे जी आपण लपविली आहे
                  आणि त्यांना माहित नाही? असे होणे कधीच शक्य नाही. पण स्वामींनाही
                  भक्तांच्या उद्धाराकरिता आणि त्यांना प्रबोध करण्यासाठी काही लीला
                  करायच्या असतात. तशीच लीला त्यादिवशी घडली. स्वामींना कोण अडविणार
                  नाही का?
                </p>
                <p>
                  असो. स्वामी प्रसाद वाटत बाळप्पाच्या हातापर्यंत आले अन फक्त एकच
                  क्षण स्वामी थांबले आणि दुसऱ्याच क्षणी बाळप्पाच्या हातात भली मोठी
                  खारीक प्रसाद म्हणुन पडली. बस्स! एका क्षणात बाळप्पानी ती खारीक
                  घट्ट पकडली आणि तेथून धूम ठोकली. न जाणो स्वामी पहातील आणि मोठ्या
                  कष्टाने मिळालेला प्रसाद स्वामी घेतला तर? बाळप्पा आपल्या घरी आले.
                  दरवाजा आतुन बंद केला. प्रसाद म्हणुन मिळालेली खारीक हृदयाशी घट्ट
                  धरली. डोळे बंद करुन अतिशय आनंदाने ते रडू लागले. मनातल्या मनात
                  स्वामींना सांगू लागले. "स्वामी का हो इतका वेळ लावलात या गरीबाला
                  प्रसाद द्यायला. या पामराकडून असा काय अपराध घडला की मला एवढी वाट
                  पहावी लागली. आज या पामराचे आज भाग्य उजळले. मला स्वामींचा प्रसाद
                  मिळाला." असे म्हणत ते लहान मुलासारखे किती तरी वेळ तो प्रसाद न
                  खाता रडत राहीले. त्यांची भाव समाधी लागली होती. एव्हढ्यात दरवाजा
                  जोरात वाजू लागला. "बाळप्पा, दार उघडा". "बाळप्पा दार उघडा.
                  स्वामींनी तुम्हांला असेल तसे बोलावले आहे.” बाळप्पा समजले की
                  स्वामींनी आपल्याला का बोलावले असावे. स्वामींपुढे जाण्याशिवाय
                  दुसरा पर्यायच नव्हता. धावत जाऊन बाळप्पा स्वामींसमोर
                  अपराध्यासारखे मान खाली घालून आणि हाताची मूठ घट्ट धरुन उभे
                  राहिले. बाळप्पाला पाहताच महाराज ओरडले, "हरामखोर हमसे नजर चुराके
                  प्रसाद लेके जाता है? तु बडा जिद्दी है. ना तु मुझे छोडेगा, ना मै
                  तुझे छोडुंगा. लाओ प्रसाद लाओ." बाळप्पांनी मुठीत घट्ट धरून
                  ठेवलेली खारीक स्वामींना देऊन टाकली. स्वामींनी ती खारीक घेतली आणि
                  बाळप्पाला अत्यंत प्रेमाने जवळ घेतले. स्वामी म्हणाले, "अरे तु या
                  प्रसादाच्या मागे काय लागला आहेस. जो प्रसाद तुला द्यायचा आहे तो
                  मी तुला कधीच दिला आहे. माझ्या मांडीवर तुला घेतले आहे. माझ्या
                  शेजारीच मांडी घालुन बस हाच तुला प्रसाद." या नंतर बाळप्पानी कधीही
                  प्रसादाचा हट्ट केला नाही.
                </p>
                <p>
                  ओळखलात का? तो कुठला प्रसाद? स्वामींच्या समाधी शेजारीच समाधी
                  घेण्याची परवानगी. जी कोणालाही मिळाली नाही. धन्य ते स्वामीगुरु
                  आणि धन्य ते शिष्य बाळप्पा!
                </p>
                <p>
                  एके दिवशी बाळप्पाना असे जाणवले की त्यांचे साधनेत एकाग्रता येत
                  नाही. त्यांनी ही गोष्ट स्वामींना सांगितली. स्वामींनी पाठीवर हात
                  फिरवला आणि काय आश्र्चर्य बाळप्पा ब्रह्मानंदी मग्न झाले.
                  बाळप्पांची ही भावसमाधी बरेच तास चालली. स्वामींनी तुळशीची माळ
                  देऊन त्यांना जप करण्यास सांगितले. त्यानंतर बाळप्पांची उत्तरोत्तर
                  आध्यात्मिक प्रगती होऊ लागली. स्वामीनी एकदा त्यांचे नाव असलेली
                  अंगठी बाळप्पांना भेट दिली आणि म्हणाले, "साधनेत निमग्न रहा. माझे
                  आशिर्वाद सदैव तुझ्या पाठीशी आहेत" या आश्वसनाने बाळप्पा भारावले
                  आणि स्वामींच्या चरणावर अश्रूंचा अभिषेक झाला. त्यांनी बाळप्पाला
                  आशिर्वादाबरोबर आपली कफनी, पादुका, दंड आणि निशाण दिले. बाळप्पाला
                  औदुंबराखाली स्वतंत्र मठ स्थापनेची आज्ञा दिली. हाच बाळप्पा मठ
                  किंवा गुरुमंदीर नावाने प्रसिद्ध आहे. गुरूमंदिरात या सर्व वस्तु
                  दर्शनास उपलब्ध आहेत. भक्तजन त्याचे दर्शन घेऊ शकतात.
                </p>
                <p>
                  बाळप्पानी मठ स्थापनेपूर्वीच भारत भ्रमण केले. स्वामींच्या
                  विचारांचा प्रसार केला. त्या प्रवासात त्यांना भक्तांकडून आदर
                  सन्मान मिळाला. हा स्वामींचाच प्रसाद नाही का!
                </p>
                <p>
                  स्वामींच्या महानिर्वाणानंतर बाळप्पा खचले. आपल्या जीवनाचा आधार
                  गेला असे त्यांना वाटू लागले. आपला कार्यकारण भाव संपला असा विचार
                  बाळप्पाच्या मनात येऊ लागला. बाळप्पा समाधीसमोर अन्नत्याग करून
                  बसले. तिसऱ्या दिवशी स्वामींनी स्वत: प्रकट होऊन बाळप्पाना
                  सांगितले, “मी इथेच आहे. मी निराकार स्वरूपात आहे.” मग बाळप्पांनी
                  पादूकातच स्वामींना पाहण्यास सुरुवात केली. एकनिष्ठेने पादूकांचीच
                  सेवा करू लागले. ते आजारी असतानाही त्यांनी पादूकांची सेवा कधी
                  सोडली नाही. स्वामींच्या निर्वाणानंतर बाळप्पानी ३२ वर्षे स्वामी
                  सेवा आणि स्वामिभक्तीचा प्रचार केला. त्यासाठी त्यांनी ओरीसा
                  कर्नाटक, बिहार, उत्तर प्रदेश, मध्यप्रदेश, राजस्थान, बंगाल या
                  प्रांतांचा दौरा केला. श्री स्वामी समर्थ या नाममंत्राचा प्रसार
                  केला.
                </p>
                <p>
                  निर्वाणाचा दिवस येताच बाळप्पानी आपला शिष्य श्री गंगाधर महाराज
                  यांना बोलावून घेतले. त्यांना विधिपूर्वक सर्वाधिकार देण्यात आले.
                  बाळप्पानी सर्वाधिकार देताना आज्ञापत्रात लिहिले, "श्री स्वामी
                  समर्थानी आम्हांवर कृपा केली. आम्ही जसे श्री समर्थांचे नाव
                  चालवले, तसे आमच्या ज्या शिष्यवर्गापैकी कोणावर कृपा होईल त्याने
                  मठ चालवावा. 'महाराज आता आमचे कसे होणार?' असे शिष्यमंडळींनी
                  विचारताच बाळप्पा म्हणाले, “अरे मी कोठेही जात नाही. फक्त या
                  आसनावरून उठून आत जाऊन बसेन”.
                </p>
                <p>
                  इ.स. १९१० मध्ये बाळप्पानी समाधी घेतली. स्वामी समर्थांच्या
                  शेवटच्या श्वासापर्यंत आणि त्यानंतर स्वतःच्या शेवटच्या
                  श्वासापर्यंत बाळप्पानी स्वामी भक्तीचा आणि स्वामी सेवेचा ध्यास
                  घेतला होता. बाळप्पा महाराजांप्रमाणे एकनिष्ठ आणि प्रामाणिक सेवक
