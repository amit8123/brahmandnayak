                <p class="fw-bold">
                  श्री. यशवंत महादेव भोसेकर
                  संतश्रेष्ठ श्री देवमामलेदार
                </p>
                <p>
                  हरीदेवी आणि महादेवपंत देशपांडे या भोसे गाव (ता. पंढरपूर, जि. सोलापूर) येथील अश्वलायन शाखेच्या कश्यप
                  गोत्री ॠग्वेदी ब्राम्हण कुटुंब होते. दोघेही उभयता धर्मप्रिय, भाविक आणि अतिथीप्रिय होते. त्यांच्या
                  घराण्यात दत्तसेवा पूर्वापार चालत आलेली होती. अशा सदाचारी कुटुंबात भाद्रपद शुद्ध १० शके १७३७ बुधवार या
                  दिवशी यशवंतचा जन्म झाला.
                </p>
                <p>
                  महादेवपंतांना दादा, यशवंत, मनोहर, आबा, रामचंद्र, प्रल्हाद, वासुदेव आणि बलराम असे आठ मुलगे आणि सखू
                  नावाची कन्या झाली. त्यांचे दुसरे पुत्ररत्न यशवंतराव हेच पुढे देव मामलेदार म्हणून ओळखले गेले. यशवंताला
                  लहानपणापासूनच दत्त भक्तीची ओढ लागली. जन्मानंतर दोन वर्षातच यशवंत सज्ञानी माणसाप्रमाणे वागू लागला.
                  त्यांचे तेज पाहून आई-वडिलांना यशवंतामधील दैवी सामर्थ्याची ओळख पटली. वयाच्या आठव्या वर्षी म्हणजे शके
                  १७४६ जेष्ठ कृ. प्रतिपदेला त्याचे मौजीबंधन करण्यात आले. यशवंताचा विवाह टेंभूर्णी येथील जिवाजी बापुजी
                  देशपांडे यांची मुलगी सुंदराबाई हिच्याशी शके १७४६ फाल्गुन कृ. सप्तमी, शुक्रवार रोजी झाला. त्यावेळी
                  सुंदराबाई अवघ्या सहा वर्षाच्या होत्या.
                </p>
                <p>
                  लग्नानंतर कळत्या वयात कुटुंबाची जबाबदारी यशवंतरावांवर आली. ते त्यांच्या मामाकडे कोपरगावला आले. इ. स.
                  १८२९ मध्ये मामांनी खटपट करुन त्यांची बदली कारकून म्हणून येवले येथे तात्पुरती नोकरी मिळवून दिली.
                  नोकरीनंतर दोन वर्षात आपल्या कामातील सचोटी, चोख काम आणि मोत्यासारखे अक्षर पाहून त्यांची कारकून म्हणून
                  दरमहा दहा रुपये पगारावर नियुक्ती झाली. वयाच्या सोळाव्या वर्षी मिळालेली नोकरी जणू त्यांच्या योग्यतेची
                  पावतीच होती. लवकरच यशवंतरावांना पाच रुपये पगार वाढ झाली. आता त्यांची बदली पारनेर तालुका कचेरीत झाली.
                  पारनेर येथे त्यांनी पाच वर्षे जबाबनीस म्हणून चांगल्या प्रकारे काम केले. नोकरीच्या निमित्त नेहमी परगावी
                  राहावे लागणार हे जाणून त्यांची पत्नी सुंदराबाई पारनेरला येऊन राहिली. सरकारी नोकरीत असताना त्यांनी
                  प्रपंच आणि परमार्थाची सांगड उत्तमपणे घातली. यशवंतरावांना परमार्थ कार्यातही सुंदराबाईंची साथ मिळू
                  लागली. यशवंतराव यांनी गोरगरीब, निराधार महिला, मुले आजारी आणि व्याधीग्रस्त यांना मदत करताना आपले सर्व
                  आयुष्य वेचले. त्या सर्वांना ते आपले कुटुंबिय मानीत असत. इ. स. १८२९ ते १८७२ तब्बल ४३ वर्षे महसूल
                  खात्यात नोकरी केली. त्यांच्या कामातील हुशारी आणि प्रामाणिकपणामुळे त्यांना खात्यात बढती मिळत गेली. या
                  नोकरीच्या काळात त्यांनी येवला, चाळीसगाव, एरंडोल, अमळनेर, शहादा, धुळे, सिंदखेडा आणि सटाणा येथे मामलेदार
                  म्हणून काम पाहिले. सटाणा येथूनच ते निवृत्त झाले.
                </p>
                <p>
                  एकदा रात्री झोपेत असताना यशवंतरावांना एक तेजस्वी महापुरुष समोर बसलेला दिसला. अजानुबाहू, दिगंबर, भव्य
                  कपाळ, डाव्या मांडीवर उजवी मांडी ओढून धरलेली, पायांचे तळवे जमिनीला टेकलेले, डोळ्यात विलक्षण तेज आसलेली
                  व्यक्ती त्यांना म्हणाली, "बेटा घबराओ नही. ये ले काम की चीज". यशवंतरावांच्या हातावर शाळीग्राम ठेवून ती
                  व्यक्ती म्हणाली, “इसकी भक्तीभावसे पूजा करना तुम्हारी मनोकामना पूरी होगी.” असे म्हणून ती व्यक्ती
                  अंतर्धान पावली. यशवंतरावांना लगेच जाग आली. जागृतावस्थेत त्यांनी पाहीले तर त्यांच्या हातात एक शाळीग्राम
                  होता. याला स्वप्न म्हणावे की सत्य हेच त्यांना उमजेना, स्वप्न म्हटले तर त्या दिव्य सत्पुरुषाने दिलेली
                  वस्तू प्रत्यक्ष त्यांच्या हातात होती. तो एक साक्षात्कार होता.
                </p>
                <p>
                  यशवंतराव निस्सिम दत्त उपासक होते. त्यांना प्रत्यक्ष दत्तात्रेयांनी दर्शन दिले होते. या दत्तभक्तीचे तेज
                  त्यांच्या व्यक्तिमत्वात दिसून येत असे. आपल्या भक्तीच्या पुण्याईने ते त्यांच्याकडे येणाऱ्या अडलेल्या
                  नाडलेल्यांच्या अडचणी दूर करीत.
                </p>
                <p>
                  यशवंतराव नोकरीच्या शेवटच्या काळात सटाणा (नाशिक) येथे मामलेदार होते. इ. स. १८७०-१८७१ महाराष्ट्रात फार
                  मोठा दुष्काळ पडला. माणसे आणि जनावरे अन्नपाण्यावाचून मृत्युमुखी पडत होती. त्यावेळी यशवंतराव बागलाण
                  तालुक्यात महसूल विभागात मामलेदार पदावर होते. त्यावेळची तालुक्यातील दुष्काळाची भीषण परिस्थिती पाहून
                  यशवंतरावांनी आपली सर्व मालमत्ता विकून टाकली आणि सर्व रक्कम लोकांमध्ये वाटून टाकली. पण दुष्काळ स्थिती
                  पाहता ही रक्कम अगदीच कमी होती. हे देव मामालेदारांना जाणवले. ते तालुका तहसीलदार होते. त्यांनी सरकारी
                  खजिन्यातील रोख रक्कमही गोरगरीबांमध्ये वाटून टाकली. ही सरकारी रक्कम थोडीथोडकी नाही तर त्याकाळी जवळपास
                  सव्वालाख रुपये होती. ही गोष्ट त्यांच्या वरिष्ठांना कळली. वरिष्ठांनी सरकारी रक्कमेचा हिशोब तपासून
                  पाहिला. आणि आश्चर्य म्हणजे सर्व सरकारी रक्कम बरोबर होती. एका पैशाचाही फरक मिळाला नाही. या ठिकाणी
                  भगवंताने चमत्कार तर केलाच, पण महाविष्णूनी यशवंतरावांना साक्षात दर्शन दिले. बाळगणं तालुक्यातील लोकांनी
                  दुष्काळात आपल्या मदतीला येणाऱ्या या तहसीलदाराला देवत्व बहाल केले. तेव्हापासून श्री. यशवंत महादेव
                  भोसेकर हे ‘देव मामलेदार’ या नावाने ओळखले जाऊ लागले.
                </p>
                <p>
                  यशवंतराव मुक्तहस्ते दानधर्म करीत. दत्तकृपेमुळे त्यांची संपत्ती कधीच कमी झाली नाही उलट 'अक्षय' राहिली.
                  तेव्हा लोकांना कळले की हे साधारण मानव नसून दैवी अवतार आहेत. पण त्यांनी स्वतःला दैवी अवतार न मानता केवळ
                  स्वामीवर विश्वास ठेवून गुरु आज्ञेप्रमाणे आपले कार्य चालूच ठेवले.
                </p>
                <p>
                  स्वामी समर्थांचा साक्षात्कार झाल्यानंतर यशवंतरावांच्यात खूप बदल झाला. मुळातच शांत आणि सात्विक
                  स्वभावाचे दत्तभक्ती परायण असलेले यशवंतराव भक्तीमार्गात गढून गेले. स्वतःच्या दत्तभक्तीने अनेक दुःखी,
                  व्याधीग्रस्त आणि संकटग्रस्त भक्तांच्या नाना प्रकारच्या अडचणी दूर केल्या. आपल्या भक्तीचे पुण्य
                  त्यांच्या पदरात टाकले. महाराज कायम भगवंत चरणाशी लीन होऊन राहत. स्वतःच्या दास्यभक्तीतून त्यांनी अनेक
                  भक्तांचा उद्धार केला.
                </p>
                <p>
                  यशवंतराव नाशिकला असताना त्यांची भेट टेंब्ये स्वामी महाराजांशी झाली. त्यावेळी टेंब्ये स्वामींच्या
                  मातोश्री सोबत होत्या. दोघेही दत्त भक्त असल्याने त्यांच्यात अध्यात्मासंबंधी बराच वेळ चर्चा झाली. शेवटी
                  निरोप घेताना यशवंतरावांनी टेंब्ये स्वामींच्या मातोश्रीना सांगितले, "हे फार मोठे अधिकारी योगी आहे.”
                  पुढील काळात टेंब्ये स्वामी प. प. वासुदेवानंद सरस्वती या नावाने प्रसिद्ध होऊन त्यांना दत्त संप्रदायात
                  त्यांना मानाचे स्थान मिळाले.
                </p>
                <p>
                  अक्कलकोटला श्री स्वामी समर्थानी अवतार घेतल्यावर त्यांच्या काही शिष्याना उपासना आणि कार्य करण्यासाठी
                  गावे नेमून दिली. स्वामींनी यशवंतरावांना सटाणा गावात कार्य करण्याची आज्ञा दिली. त्यांच्या कार्यात
                  आलेल्या अनेक अनुभवातून आणि दुष्काळात घडलेल्या दैवी चमत्कारांमुळे गावातील सर्व त्यांना देव मामलेदार
                  म्हणून ओळखू लागले. पुढे तीच त्यांची ओळख राहिली.
                </p>
                <p>
                  श्री देव मामलेदारांनी त्यांच्या कार्यकाळात अनेक लीला केल्या. हजारो लोकांना मदत केली. त्यांच्या जीवनाचा
                  उद्धार केला. आयुष्याच्या अखेरच्या क्षणापर्यंत दत्त उपासना आणि स्वामी कार्यात असताना श्री देव मामलेदार
                  यांनी २७ डिसेंबर १८८७ (मार्गशीर्ष कृ. ११ शके १८०९) रोजी सटाणा येथे आपला देह ठेवला. श्री देव
                  मामलेदारांचे कृपेने सर्व इच्छा पूर्ण होतात असा आजही भक्तांचा विश्वास आहे. प. पू. देव मामलेदार यशवंत
                  महाराज आपल्या सोबत आहेत असा विश्वास प्रत्येक भक्ताला आहे.
                </p>
                <p>
                  संतश्रेष्ठ श्री देवमामालेदार यांची शिष्य परंपरा त्याच्या पश्चात आजही सुरु आहे. त्याच्या महान अधिकारी
                  शिष्यांपैकी ३ शिष्य म्हणजे श्री सदानंद स्वामी (काशी), श्री नारायण स्वामी (गोदातीर) आणि श्री पद्मनाभ
                  स्वामी (मुंबई) हे होते.
                </p>
              </article>
